// Oracle record of the last GPU/CPU write into an image (KYTY_ORACLE_FLIP log).
enum class ImageWriteKind : uint8_t {
	None,
	RenderTarget,
	Storage,
	CopyImage,
	Resolve,
	CopyMip,
	UploadBuffer,
	CopyWithBuffer,
};
struct ImageWrite {
	ImageWriteKind kind   = ImageWriteKind::None;
	uint64_t       shader = 0;  // shader hash for Storage writes
	uint64_t       serial = 0;  // global order of the write
};
[[nodiscard]] uint64_t NextImageWriteSerial() noexcept;

